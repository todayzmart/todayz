// Command eventgen validates shared/telemetry/events/*.yaml and generates
//
//   - backend/gen/events: a copy of the files and an embed.go (the API loads
//     them with eventcat.Load(events.FS) and validates /v1/events with them);
//   - shared/telemetry/src/gen/events.ts: the typed emitter's event map.
//
// An event name defined in two files fails the build (05 §2.6). `make gen`
// runs it (mk/26-events.mk).
//
//	go run ./internal/devtools/eventgen -in ../shared/telemetry/events -go gen/events -ts ../shared/telemetry/src/gen/events.ts
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/todayz/backend/internal/platform/eventcat"
)

func main() {
	in := flag.String("in", "../shared/telemetry/events", "directory with <domain>.yaml files")
	goOut := flag.String("go", "gen/events", "Go package directory")
	tsOut := flag.String("ts", "../shared/telemetry/src/gen/events.ts", "TypeScript output file")
	flag.Parse()
	if err := run(*in, *goOut, *tsOut); err != nil {
		fmt.Fprintln(os.Stderr, "eventgen:", err)
		os.Exit(1)
	}
}

func run(in, goOut, tsOut string) error {
	cat, err := eventcat.Load(os.DirFS(in))
	if err != nil {
		return err
	}
	names, err := filepath.Glob(filepath.Join(in, "*.yaml"))
	if err != nil {
		return err
	}
	sort.Strings(names)
	if err := os.RemoveAll(goOut); err != nil {
		return err
	}
	if err := os.MkdirAll(goOut, 0o750); err != nil {
		return err
	}
	for _, n := range names {
		b, err := os.ReadFile(n) // #nosec G304 -- inputs are the repo's own event files
		if err != nil {
			return err
		}
		if err := os.WriteFile(filepath.Join(goOut, filepath.Base(n)), b, 0o600); err != nil { // #nosec G703 -- goOut is the -go flag of make gen
			return err
		}
	}
	src := "// Code generated by eventgen from shared/telemetry/events; DO NOT EDIT.\n\n" +
		"// Package events embeds the product event catalogue (05 §2.6).\n" +
		"package events\n\nimport \"embed\"\n\n// FS holds every shared/telemetry/events/<domain>.yaml.\n//\n//go:embed *.yaml\nvar FS embed.FS\n"
	fmtd, err := format.Source([]byte(src))
	if err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(goOut, "embed.go"), fmtd, 0o600); err != nil { // #nosec G703 -- goOut is the -go flag of make gen
		return err
	}
	if err := os.MkdirAll(filepath.Dir(tsOut), 0o750); err != nil {
		return err
	}
	return os.WriteFile(tsOut, []byte(TS(cat)), 0o600) // #nosec G703 -- tsOut is the -ts flag of make gen
}

// TS renders the event map for the typed emitter.
func TS(cat *eventcat.Catalogue) string {
	var b bytes.Buffer
	b.WriteString("// Code generated by eventgen from shared/telemetry/events; DO NOT EDIT.\n\n")
	b.WriteString("/** Props of every product event, by name (05 §2.6). */\nexport interface EventProps {\n")
	var client []string
	for _, n := range cat.Names() {
		e, _ := cat.Event(n)
		if e.Emitter == eventcat.EmitterClient {
			client = append(client, n)
		}
		fmt.Fprintf(&b, "  %s: {", n)
		pn := make([]string, 0, len(e.Props))
		for p := range e.Props {
			pn = append(pn, p)
		}
		sort.Strings(pn)
		for _, p := range pn {
			opt := ""
			if e.Props[p].Optional {
				opt = "?"
			}
			fmt.Fprintf(&b, " %s%s: %s;", p, opt, tsType(e.Props[p]))
		}
		b.WriteString(" };\n")
	}
	b.WriteString("}\n\n/** Every event name. */\nexport type EventName = keyof EventProps;\n\n")
	b.WriteString("/** Events a client may post; the server emits the rest (facts come from the server). */\nexport const CLIENT_EVENTS = [")
	for i, n := range client {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(&b, "'%s'", n)
	}
	b.WriteString("] as const;\n\nexport type ClientEventName = (typeof CLIENT_EVENTS)[number] & EventName;\n")
	return b.String()
}

func tsType(p eventcat.Prop) string {
	switch p.Type {
	case eventcat.TypeEnum:
		vs := make([]string, len(p.Values))
		for i, v := range p.Values {
			vs[i] = "'" + v + "'"
		}
		return strings.Join(vs, " | ")
	case eventcat.TypeInt, eventcat.TypeNumber:
		return "number"
	case eventcat.TypeBool:
		return "boolean"
	default:
		return "string"
	}
}
