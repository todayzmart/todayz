package main

import (
	"bytes"
	"context"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
)

// runCodegen writes gen/api/spec (the embedded bundle) and, for every domain
// with at least one operation, gen/api/<domain>/api.gen.go from oapi-codegen:
// types, the chi server and the strict server for that domain's tag. Domains
// are packages named <domain without hyphens>api (admin-orders → adminordersapi).
func runCodegen(api, bundle, out, tool string, w io.Writer) error {
	doc, err := loadDoc(context.Background(), bundle)
	if err != nil {
		return err
	}
	domains := map[string]bool{}
	for _, item := range doc.Paths.Map() {
		for _, op := range item.Operations() {
			for _, t := range op.Tags {
				domains[t] = true
			}
		}
	}

	if err := os.RemoveAll(out); err != nil {
		return err
	}
	if err := writeSpecPackage(bundle, filepath.Join(out, "spec")); err != nil {
		return err
	}
	for _, d := range sortedKeys(domains) {
		dir := filepath.Join(out, d)
		if err := os.MkdirAll(dir, 0o750); err != nil {
			return err
		}
		pkg := strings.ReplaceAll(d, "-", "") + "api"
		cmd := exec.CommandContext(context.Background(), tool, // #nosec G204 -- the -tool flag of make gen
			"-generate", "types,chi-server,strict-server",
			"-include-tags", d,
			"-package", pkg,
			"-o", filepath.Join(dir, "api.gen.go"),
			bundle)
		var stderr bytes.Buffer
		cmd.Stderr = &stderr
		if err := cmd.Run(); err != nil {
			return fmt.Errorf("oapi-codegen for %s: %w\n%s", d, err, stderr.String())
		}
		if err := os.WriteFile(filepath.Join(dir, "register.gen.go"), []byte(registerSource(pkg, d)), 0o600); err != nil { // #nosec G703 -- dir is under the -out flag of make gen
			return err
		}
	}
	fmt.Fprintf(w, "apigen codegen: %d domain packages + spec -> %s\n", len(domains), out)
	return nil
}

// registerSource is gen/api/<domain>/register.gen.go: the one way a domain
// mounts its generated server (D-100 M2). Both oapi-codegen error paths go
// through httpx/openapi, so a request it cannot bind and an error a handler
// returns both answer problem+json with a generic detail, never the plain
// text that echoes the request. cmd/todayz's
// TestDomainsRegisterThroughGeneratedRegister refuses a domain that calls
// NewStrictHandler or HandlerWithOptions itself.
func registerSource(pkg, domain string) string {
	return `// Code generated by apigen from backend/api; DO NOT EDIT.

package ` + pkg + `

import (
	"github.com/go-chi/chi/v5"

	"github.com/todayz/backend/internal/platform/httpx/openapi"
)

// Register mounts every ` + domain + ` operation on r through the strict server
// with the platform's problem+json error handlers (D-100). Domains call it from
// cmd/todayz/routes_` + domain + `.go and nothing else.
func Register(r chi.Router, ssi StrictServerInterface, middlewares ...StrictMiddlewareFunc) {
	si := NewStrictHandlerWithOptions(ssi, middlewares, StrictHTTPServerOptions(openapi.StrictOptions()))
	HandlerWithOptions(si, ChiServerOptions{BaseRouter: r, ErrorHandlerFunc: openapi.StrictRequestError})
}
`
}

// writeSpecPackage copies the bundle next to an embed.go so the API embeds the
// contract it validates against (internal/platform/httpx/openapi).
func writeSpecPackage(bundle, dir string) error {
	if err := os.MkdirAll(dir, 0o750); err != nil {
		return err
	}
	b, err := os.ReadFile(bundle) // #nosec G304 -- the -bundle flag of make gen
	if err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(dir, "openapi.yaml"), b, 0o600); err != nil { // #nosec G703 -- dir is under the -out flag of make gen
		return err
	}
	src := `// Code generated by apigen from backend/api; DO NOT EDIT.

// Package spec embeds the bundled OpenAPI contract (04 §1). The request
// validator (httpx/openapi) and the contract tests read it from here.
package spec

import _ "embed"

// Bundle is backend/api/openapi.yaml as bundled by make gen.
//
//go:embed openapi.yaml
var Bundle []byte
`
	return os.WriteFile(filepath.Join(dir, "embed.go"), []byte(src), 0o600)
}
