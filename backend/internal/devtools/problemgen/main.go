// Command problemgen validates backend/api/problems/*.yaml and generates
// backend/gen/problems: a copy of the files, an embed.go that embeds them, and
// codes.go with one Go constant per code. `make gen` runs it (gen-backend).
//
//	go run ./internal/devtools/problemgen -in api/problems -out gen/problems
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"

	"github.com/todayz/backend/internal/platform/httpx/problem/registry"
)

func main() {
	in := flag.String("in", "api/problems", "directory with <domain>.yaml files")
	out := flag.String("out", "gen/problems", "output package directory")
	flag.Parse()
	if err := run(*in, *out); err != nil {
		fmt.Fprintln(os.Stderr, "problemgen:", err)
		os.Exit(1)
	}
}

func run(in, out string) error {
	reg, err := registry.Load(os.DirFS(in))
	if err != nil {
		return err
	}
	names, err := filepath.Glob(filepath.Join(in, "*.yaml"))
	if err != nil {
		return err
	}
	sort.Strings(names)
	if err := os.RemoveAll(out); err != nil {
		return err
	}
	if err := os.MkdirAll(out, 0o750); err != nil {
		return err
	}
	for _, n := range names {
		b, err := os.ReadFile(n) // #nosec G304 -- inputs are the repo's own problem files
		if err != nil {
			return err
		}
		if err := os.WriteFile(filepath.Join(out, filepath.Base(n)), b, 0o600); err != nil { // #nosec G703 -- out is the -out flag of make gen
			return err
		}
	}

	var src bytes.Buffer
	src.WriteString("// Code generated by problemgen from backend/api/problems; DO NOT EDIT.\n\n")
	src.WriteString("// Package problems embeds the problem code registry (04 §1.4, D-24).\n")
	src.WriteString("package problems\n\nimport \"embed\"\n\n")
	src.WriteString("// FS holds every backend/api/problems/<domain>.yaml.\n//\n//go:embed *.yaml\nvar FS embed.FS\n")
	if err := writeGo(filepath.Join(out, "embed.go"), src.Bytes()); err != nil {
		return err
	}

	src.Reset()
	src.WriteString("// Code generated by problemgen from backend/api/problems; DO NOT EDIT.\n\npackage problems\n\n")
	src.WriteString("// Registered problem codes. Use these, not string literals.\nconst (\n")
	for _, c := range reg.Codes() {
		e, _ := reg.Lookup(c)
		fmt.Fprintf(&src, "\t// %s is %d (%s.yaml): %s\n\t%s = %q\n", registry.GoName(c), e.Status, e.Domain, e.Title, registry.GoName(c), c)
	}
	src.WriteString(")\n")
	if err := writeGo(filepath.Join(out, "codes.go"), src.Bytes()); err != nil {
		return err
	}
	fmt.Printf("problemgen: %d codes -> %s\n", len(reg.Codes()), out)
	return nil
}

func writeGo(path string, src []byte) error {
	b, err := format.Source(src)
	if err != nil {
		return fmt.Errorf("%s: %w", path, err)
	}
	return os.WriteFile(path, b, 0o600)
}
