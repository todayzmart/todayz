// Package cssgen builds the mocks UI stylesheet (assets/tz.css) from the
// TodayZ design system: tokens.json values as :root custom properties, then
// the component bundle with its web-font @import removed. The mocks UI runs
// offline, so the display and sans families become system font stacks.
package cssgen

import (
	"bytes"
	"encoding/json"
	"fmt"
	"strings"
)

// System font stacks replace Figtree and Anek (no network fonts offline).
const (
	SystemSans    = `system-ui, -apple-system, "Segoe UI", Roboto, "Noto Sans", "Helvetica Neue", Arial, sans-serif`
	SystemDisplay = SystemSans
	SystemMono    = `ui-monospace, SFMono-Regular, Menlo, Consolas, "Liberation Mono", monospace`
)

type token struct {
	Name  string          `json:"name"`
	Value json.RawMessage `json:"value"`
}

type group struct {
	Tokens []token `json:"tokens"`
}

type tokensFile struct {
	Color   group `json:"color"`
	Spacing group `json:"spacing"`
	Radius  group `json:"radius"`
	Shadow  group `json:"shadow"`
	Size    group `json:"size"`
	ZIndex  group `json:"zIndex"`
}

// value returns a token's light value: a plain string or number, or {"light": ...}.
func value(raw json.RawMessage) (string, error) {
	var s string
	if json.Unmarshal(raw, &s) == nil {
		return s, nil
	}
	var n json.Number
	if json.Unmarshal(raw, &n) == nil {
		return n.String(), nil
	}
	var themed map[string]json.RawMessage
	if err := json.Unmarshal(raw, &themed); err != nil {
		return "", fmt.Errorf("unsupported token value %s", raw)
	}
	light, ok := themed["light"]
	if !ok {
		return "", fmt.Errorf("token value has no light theme: %s", raw)
	}
	return value(light)
}

// Generate returns the full stylesheet.
func Generate(tokensJSON, bundleCSS []byte) ([]byte, error) {
	var t tokensFile
	if err := json.Unmarshal(tokensJSON, &t); err != nil {
		return nil, fmt.Errorf("tokens.json: %w", err)
	}
	var b bytes.Buffer
	b.WriteString("/* GENERATED by e2e/mocks/cmd/gencss from the design system's tokens.json and\n")
	b.WriteString("   components/bundle.css. Do not edit; run `go run ./cmd/gencss` in e2e/mocks.\n")
	b.WriteString("   Light theme only. Web fonts removed: the mocks UI runs offline. */\n\n")
	b.WriteString(":root {\n")
	groups := []struct {
		name string
		g    group
	}{{"color", t.Color}, {"spacing", t.Spacing}, {"radius", t.Radius}, {"shadow", t.Shadow}, {"size", t.Size}, {"zIndex", t.ZIndex}}
	count := 0
	for _, g := range groups {
		fmt.Fprintf(&b, "  /* %s */\n", g.name)
		for _, tk := range g.g.Tokens {
			if tk.Name == "" {
				return nil, fmt.Errorf("tokens.json: %s token without a name", g.name)
			}
			v, err := value(tk.Value)
			if err != nil {
				return nil, fmt.Errorf("tokens.json: %s.%s: %w", g.name, tk.Name, err)
			}
			fmt.Fprintf(&b, "  --%s: %s;\n", tk.Name, v)
			count++
		}
	}
	if count == 0 {
		return nil, fmt.Errorf("tokens.json: no tokens found")
	}
	b.WriteString("  /* type (system fonts) */\n")
	fmt.Fprintf(&b, "  --font-display: %s;\n", SystemDisplay)
	fmt.Fprintf(&b, "  --font-sans: %s;\n", SystemSans)
	fmt.Fprintf(&b, "  --font-mono: %s;\n", SystemMono)
	b.WriteString("}\n\n")

	for _, line := range strings.SplitAfter(string(bundleCSS), "\n") {
		if strings.HasPrefix(strings.TrimSpace(line), "@import") {
			continue
		}
		b.WriteString(line)
	}
	if !bytes.HasSuffix(b.Bytes(), []byte("\n")) {
		b.WriteByte('\n')
	}
	return b.Bytes(), nil
}
