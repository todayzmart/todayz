// MSW handlers from the contract's examples (W0-04; 08 §3.5). Pure: renderHandlers
// takes the bundled OpenAPI document (as JSON) and returns the TypeScript source of
// src/mocks/handlers.gen.ts. scripts/gen.mjs writes it; test/msw.test.ts covers it.
//
// One handler per operation, named after its operationId, answering the first 2xx
// response's `application/json` example (the contract lint makes sure every 2xx
// response has one). Paths match any origin (`*/v1/me/orders/:oid`), so the same
// handlers serve a Vite dev server, Storybook and vitest. A response without a
// body (204) answers empty; a response whose body is not JSON (an image, an SSE
// stream) gets no handler and is listed in the header comment.

const METHODS = ['get', 'post', 'put', 'patch', 'delete'];

// An operationId becomes an exported identifier, so it is checked, not quoted.
const IDENT = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

/** A string for the generated source: always JSON-quoted, never interpolated raw (D-100, security L-4). */
export function literal(value) {
  return JSON.stringify(value, null, 2).replaceAll('\n', '\n    ');
}

/** Text for a `//` or `/** *\/` comment: no line break can end the comment line, no `*\/` can close it. */
export function comment(text) {
  return String(text)
    .replaceAll(/[\r\n\u{2028}\u{2029}]/gu, ' ')
    .replaceAll('*/', '* /');
}

// `/v1/me/orders/{oid}` -> `*` + `/v1/me/orders/:oid` (MSW path syntax, any origin).
export function mswPath(path) {
  return '*' + path.replaceAll(/\{([^}]+)\}/g, ':$1');
}

/** The first example of a media type: `example`, else the first entry of `examples`. */
export function firstExample(mediaType) {
  if (!mediaType) return undefined;
  if ('example' in mediaType) return { found: true, value: mediaType.example };
  const examples = mediaType.examples ?? {};
  const first = Object.keys(examples)[0];
  if (first === undefined) return undefined;
  return { found: true, value: examples[first]?.value };
}

/** Picks the success response an operation's handler answers with. */
export function successResponse(operation) {
  const statuses = Object.keys(operation.responses ?? {})
    .filter((s) => /^2\d\d$/.test(s))
    .sort();
  const status = statuses[0];
  if (status === undefined) return undefined;
  const response = operation.responses[status];
  const content = response?.content ?? {};
  const json = content['application/json'];
  if (Object.keys(content).length === 0) return { status: Number(status), empty: true };
  if (!json) return { status: Number(status), skipped: Object.keys(content).join(', ') };
  const example = firstExample(json);
  if (!example) return { status: Number(status), skipped: 'no example' };
  return { status: Number(status), body: example.value };
}

/** Every operation of the document in path order: {id, method, path, summary, response}. */
export function operations(doc) {
  const out = [];
  for (const path of Object.keys(doc.paths ?? {}).sort()) {
    const item = doc.paths[path];
    for (const method of METHODS) {
      const op = item[method];
      if (!op) continue;
      if (!op.operationId) throw new Error(`${method.toUpperCase()} ${path} has no operationId`);
      if (!IDENT.test(op.operationId)) {
        throw new Error(`${method.toUpperCase()} ${path}: operationId ${JSON.stringify(op.operationId)} is not an identifier`);
      }
      out.push({
        id: op.operationId,
        method,
        path,
        summary: op.summary ?? '',
        response: successResponse(op),
      });
    }
  }
  return out;
}

/** The TypeScript source of handlers.gen.ts for the bundled document. */
export function renderHandlers(doc) {
  const ops = operations(doc);
  const handlers = ops.filter((o) => o.response && !o.response.skipped);
  const skipped = ops.filter((o) => !o.response || o.response.skipped);
  const lines = [
    '// Code generated by @todayz/api-client scripts/gen.mjs from backend/api/openapi.yaml; DO NOT EDIT.',
    '//',
    '// One MSW handler per operation, answering the first 2xx example of the contract.',
    '// Override one in a test or story with setupServer(...handlers).use(http.get(...)).',
  ];
  if (skipped.length > 0) {
    lines.push('//', '// Without a handler (no JSON success response):');
    for (const o of skipped) {
      lines.push(comment(`//   ${o.method.toUpperCase()} ${o.path} (${o.id}): ${o.response?.skipped ?? 'no 2xx response'}`));
    }
  }
  lines.push('', "import { http, HttpResponse } from 'msw';", '');
  lines.push('/** Example answers by operationId: method, path, status and body. */');
  lines.push('export const examples = {');
  for (const o of handlers) {
    const body = o.response.empty ? 'undefined' : literal(o.response.body);
    lines.push(
      `  ${o.id}: { method: ${literal(o.method.toUpperCase())}, path: ${literal(o.path)}, status: ${Number(o.response.status)}, body: ${body} },`,
    );
  }
  lines.push('} as const;', '');
  for (const o of handlers) {
    const title = o.summary ? `: ${o.summary}` : '';
    lines.push(`/** ${comment(`${o.method.toUpperCase()} ${o.path}${title}`)} */`);
    const answer = o.response.empty
      ? `new HttpResponse(null, { status: ${Number(o.response.status)} })`
      : `HttpResponse.json(examples.${o.id}.body, { status: ${Number(o.response.status)} })`;
    lines.push(`export const ${o.id} = http.${o.method}(${literal(mswPath(o.path))}, () => ${answer});`, '');
  }
  lines.push('/** Every handler, in path order. */');
  lines.push(`export const handlers = [${handlers.map((o) => o.id).join(', ')}];`, '');
  return lines.join('\n');
}
