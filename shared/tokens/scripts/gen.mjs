#!/usr/bin/env node
// Generates @todayz/tokens from the design source (W0-05). Output goes to generated/ (git-ignored).
//
//   generated/tokens.css   CSS custom properties on :root (light theme only)
//   generated/tokens.ts    typed constants for TS code
//   generated/tokens.json  flat name -> value map for Node tools (vite configs, tests)
//   generated/bundle.css   design/source/components/bundle.css without the Google Fonts @import
//   generated/fonts.css    self-hosted @font-face rules (Anek, Figtree, Noto Sans) + woff2 files in fonts/
//   generated/icons/       PWA icons and favicons cut from the bag mark
//
// Run with `make gen` (or `pnpm --filter @todayz/tokens gen`). Never edit generated/ by hand.
import { createRequire } from 'node:module';
import { copyFile, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const pkg = resolve(here, '..');
const designDir = resolve(pkg, '../../design', 'source');
const out = join(pkg, 'generated');
const require = createRequire(import.meta.url);

const HEADER = 'Generated by shared/tokens/scripts/gen.mjs from design/source. Do not edit.';

/** Which fontsource subsets we ship per family: the scripts of the five launch languages only. */
export const FONT_PACKAGES = [
  { pkg: '@fontsource-variable/anek-latin', subsets: ['latin', 'latin-ext'] },
  { pkg: '@fontsource-variable/anek-devanagari', subsets: ['devanagari'] },
  { pkg: '@fontsource-variable/anek-kannada', subsets: ['kannada'] },
  { pkg: '@fontsource-variable/anek-telugu', subsets: ['telugu'] },
  { pkg: '@fontsource-variable/anek-tamil', subsets: ['tamil'] },
  { pkg: '@fontsource-variable/figtree', subsets: ['latin', 'latin-ext'] },
  { pkg: '@fontsource-variable/noto-sans-devanagari', subsets: ['devanagari'] },
  { pkg: '@fontsource-variable/noto-sans-kannada', subsets: ['kannada'] },
  { pkg: '@fontsource-variable/noto-sans-telugu', subsets: ['telugu'] },
  { pkg: '@fontsource-variable/noto-sans-tamil', subsets: ['tamil'] },
];

const lightValue = (v) => (v && typeof v === 'object' ? (v.light ?? Object.values(v)[0]) : v);

/** Flattens tokens.json into ordered [name, value] pairs, the same names the design harness uses. */
export function flattenTokens(t) {
  const vars = [];
  for (const tk of t.color.tokens) vars.push([tk.name, lightValue(tk.value), 'color']);
  for (const fam of ['spacing', 'radius', 'shadow', 'size', 'zIndex']) {
    for (const tk of t[fam].tokens) vars.push([tk.name, String(lightValue(tk.value)), fam]);
  }
  for (const [k, v] of Object.entries(t.type.families)) vars.push([`font-${k}`, v, 'font']);
  for (const g of t.type.groups) {
    for (const s of g.styles) {
      vars.push([`type-${s.name}`, `${s.fontWeight} ${s.fontSize}/${s.lineHeight} var(--font-${g.family})`, 'type']);
      vars.push([`type-${s.name}-tracking`, s.letterSpacing ?? 'normal', 'type']);
    }
  }
  return vars;
}

function tokensCss(vars) {
  const lines = vars.map(([n, v]) => `  --${n}: ${v};`);
  return `/* ${HEADER} */\n:root {\n  color-scheme: light;\n${lines.join('\n')}\n}\n`;
}

function tokensTs(vars) {
  const groups = new Map();
  for (const [n, v, kind] of vars) {
    if (!groups.has(kind)) groups.set(kind, []);
    groups.get(kind).push([n, v]);
  }
  const names = { color: 'color', spacing: 'space', radius: 'radius', shadow: 'shadow', size: 'size', zIndex: 'zIndex', font: 'fontFamily', type: 'typeStyle' };
  let ts = `// ${HEADER}\n\n`;
  for (const [kind, entries] of groups) {
    ts += `export const ${names[kind]} = {\n`;
    for (const [n, v] of entries) ts += `  ${JSON.stringify(n)}: ${JSON.stringify(v)},\n`;
    ts += `} as const;\n\n`;
  }
  ts += `/** Every CSS custom property @todayz/tokens defines on :root (without the leading --). */\n`;
  ts += `export const tokenNames = ${JSON.stringify(vars.map(([n]) => n), null, 2)} as const;\n\n`;
  ts += `export type TokenName = (typeof tokenNames)[number];\n`;
  ts += `export type ColorToken = keyof typeof color;\n\n`;
  ts += `/** \`var(--name)\` for a token, typed so a typo fails the build. */\n`;
  ts += `export const cssVar = (name: TokenName): string => \`var(--\${name})\`;\n\n`;
  ts += `/** Theme colour for the PWA manifest and <meta name="theme-color">. */\n`;
  ts += `export const themeColor = color.bg;\n`;
  return ts;
}

/** bundle.css without any @import of Google Fonts; fonts come from fonts.css instead. */
export function stripRemoteImports(css) {
  return css
    .split('\n')
    .filter((l) => !/^\s*@import\s+url\(\s*['"]?https?:/i.test(l))
    .join('\n');
}

async function fontsCss() {
  const fontsOut = join(out, 'fonts');
  await mkdir(fontsOut, { recursive: true });
  let css = `/* ${HEADER} Self-hosted fonts: no request ever goes to a font CDN. */\n`;
  for (const { pkg: name, subsets } of FONT_PACKAGES) {
    const root = dirname(require.resolve(`${name}/package.json`));
    const meta = JSON.parse(await readFile(join(root, 'metadata.json'), 'utf8'));
    const family = meta.family; // e.g. "Anek Devanagari": the name tokens.json uses
    const src = await readFile(join(root, 'wght.css'), 'utf8');
    const blocks = src.match(/\/\*[^*]*\*\/\s*@font-face\s*{[^}]*}/g) ?? [];
    let kept = 0;
    for (const block of blocks) {
      const id = block.match(/\/\*\s*([^*]+?)\s*\*\//)?.[1] ?? '';
      const subset = subsets.find((s) => id === `${meta.id}-${s}-wght-normal`);
      if (!subset) continue;
      const file = block.match(/url\(\.\/files\/([^)]+)\)/)?.[1];
      if (!file) throw new Error(`no file in ${id}`);
      await copyFile(join(root, 'files', file), join(fontsOut, file));
      css += `\n/* ${id} */\n` + block
        .replace(/\/\*[^*]*\*\/\s*/, '')
        .replace(/font-family:\s*'[^']+'/, `font-family: '${family}'`)
        .replace(/url\(\.\/files\//, 'url(./fonts/') + '\n';
      kept++;
    }
    if (kept !== subsets.length) throw new Error(`${name}: expected ${subsets.length} subsets, found ${kept}`);
  }
  return css;
}

async function icons() {
  const { default: sharp } = await import('sharp');
  const iconsOut = join(out, 'icons');
  await mkdir(iconsOut, { recursive: true });
  const src = join(designDir, 'assets', 'Logos', 'todayz-bag-mark.png');
  // The mark sits on an off-white ground; trim it so we control the padding on pure white.
  const mark = await sharp(src).trim({ threshold: 12 }).toBuffer();
  const white = { r: 255, g: 255, b: 255, alpha: 1 };
  const onWhite = async (size, scale, file) => {
    const inner = Math.round(size * scale);
    const m = await sharp(mark).resize(inner, inner, { fit: 'contain', background: white }).toBuffer();
    await sharp({ create: { width: size, height: size, channels: 4, background: white } })
      .composite([{ input: m, gravity: 'center' }])
      .png({ compressionLevel: 9, palette: true, quality: 95, effort: 10 })
      .toFile(join(iconsOut, file));
  };
  // "any" icons: the mark fills most of the square. Maskable: inside the 80% safe zone.
  await onWhite(512, 0.84, 'icon-512.png');
  await onWhite(192, 0.84, 'icon-192.png');
  await onWhite(512, 0.62, 'maskable-512.png');
  await onWhite(180, 0.78, 'apple-touch-icon.png');
  await onWhite(48, 0.92, 'favicon-48.png');
  await onWhite(32, 0.94, 'favicon-32.png');
  await onWhite(96, 0.96, 'mark-96.png');
}

async function main() {
  const t = JSON.parse(await readFile(join(designDir, 'tokens.json'), 'utf8'));
  await rm(out, { recursive: true, force: true });
  await mkdir(out, { recursive: true });
  const vars = flattenTokens(t);
  await writeFile(join(out, 'tokens.css'), tokensCss(vars));
  await writeFile(join(out, 'tokens.ts'), tokensTs(vars));
  await writeFile(join(out, 'tokens.json'), JSON.stringify(Object.fromEntries(vars.map(([n, v]) => [n, v])), null, 2) + '\n');
  const bundle = await readFile(join(designDir, 'components', 'bundle.css'), 'utf8');
  await writeFile(join(out, 'bundle.css'), `/* ${HEADER} */\n` + stripRemoteImports(bundle));
  await writeFile(join(out, 'fonts.css'), await fontsCss());
  await icons();
  console.log(`tokens: ${vars.length} vars, ${FONT_PACKAGES.length} font families, icons -> shared/tokens/generated`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main();
}
