// Command envtool manages local env keys without ever printing a value (D-18).
//
//	envtool generate -env .env.local            add missing app keys; prints "generated: NAME"
//	envtool check -env .env.local -example .env.example
//	                                              prints "NAME set" / "NAME missing"
//	envtool leakscan -env .env.local FILE...     exits 1 if any value (raw, hex, base64) is in FILE;
//	                                              prints only "leak: NAME in FILE (form)"
//	envtool egress-sink -port-file F -log L      a proxy that refuses every request and logs
//	                                              the host it was asked for (used by scripts/no-egress.sh)
package main

import (
	"bufio"
	"bytes"
	"crypto/ed25519"
	"crypto/rand"
	"encoding/base64"
	"encoding/hex"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
	"time"
)

// AppKeys is the D-18 table, in the order make setup generates them, then
// SHARE_PREVIEW_KEY (W3-16: the share-preview Pages Function's secret).
var AppKeys = []string{
	"JWT_SIGNING_KEYS",
	"JWT_CURRENT_KID",
	"ORDER_CODE_ENC_KEY",
	"ORDER_CODE_HMAC_KEY",
	"BILL_QR_SIGNING_KEY",
	"PII_ENC_KEY",
	"PII_HASH_KEY",
	"DEVICE_SECRET_ENC_KEY",
	"TOTP_ENC_KEY",
	"SHARE_PREVIEW_KEY",
}

func main() {
	if len(os.Args) < 2 {
		usage()
	}
	var err error
	switch os.Args[1] {
	case "generate":
		err = runGenerate(os.Args[2:], os.Stdout)
	case "check":
		err = runCheck(os.Args[2:], os.Stdout)
	case "leakscan":
		err = runLeakscan(os.Args[2:], os.Stdout)
	case "egress-sink":
		err = runEgressSink(os.Args[2:])
	default:
		usage()
	}
	if err != nil {
		// Errors never contain values: every error below is built from names and paths only.
		fmt.Fprintln(os.Stderr, "envtool:", err)
		os.Exit(1)
	}
}

func usage() {
	fmt.Fprintln(os.Stderr, "usage: envtool generate|check|leakscan|egress-sink [flags]")
	os.Exit(2)
}

// ---------------------------------------------------------------- env file

var nameRe = regexp.MustCompile(`^[A-Z][A-Z0-9_]*$`)

// EnvFile is a parsed dotenv file. Only NAME=VALUE lines are understood;
// values may be wrapped in single or double quotes.
type EnvFile struct {
	Values map[string]string
	Order  []string
}

func readEnv(path string) (*EnvFile, error) {
	ef := &EnvFile{Values: map[string]string{}}
	f, err := os.Open(path)
	if errors.Is(err, os.ErrNotExist) {
		return ef, nil
	}
	if err != nil {
		return nil, fmt.Errorf("open %s: %w", path, errors.Unwrap(err))
	}
	defer f.Close()
	sc := bufio.NewScanner(f)
	sc.Buffer(make([]byte, 1<<20), 1<<20)
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		line = strings.TrimPrefix(line, "export ")
		name, val, ok := strings.Cut(line, "=")
		if !ok || !nameRe.MatchString(name) {
			continue
		}
		val = unquote(strings.TrimSpace(val))
		if _, seen := ef.Values[name]; !seen {
			ef.Order = append(ef.Order, name)
		}
		ef.Values[name] = val
	}
	if err := sc.Err(); err != nil {
		return nil, fmt.Errorf("read %s: %w", path, err)
	}
	return ef, nil
}

func unquote(v string) string {
	if len(v) >= 2 && (v[0] == '\'' && v[len(v)-1] == '\'' || v[0] == '"' && v[len(v)-1] == '"') {
		return v[1 : len(v)-1]
	}
	return v
}

// appendEnv appends lines atomically: it rewrites the file through a temp file
// with mode 0600 so a crash never leaves a half-written key.
func appendEnv(path string, lines []string) error {
	old, err := os.ReadFile(path)
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return fmt.Errorf("read %s", path)
	}
	var buf bytes.Buffer
	if len(old) == 0 {
		buf.WriteString("# Local env for TodayZ. Generated by `make setup`. Never commit, print or paste these values.\n")
	} else {
		buf.Write(old)
		if old[len(old)-1] != '\n' {
			buf.WriteByte('\n')
		}
	}
	for _, l := range lines {
		buf.WriteString(l)
		buf.WriteByte('\n')
	}
	tmp, err := os.CreateTemp(filepath.Dir(path), ".envtool-*")
	if err != nil {
		return fmt.Errorf("create temp file next to %s", path)
	}
	defer os.Remove(tmp.Name())
	if err := tmp.Chmod(0o600); err != nil {
		return err
	}
	if _, err := tmp.Write(buf.Bytes()); err != nil {
		return fmt.Errorf("write %s", path)
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	return os.Rename(tmp.Name(), path)
}

// ---------------------------------------------------------------- generate

type jwk struct {
	Kty string `json:"kty"`
	Crv string `json:"crv"`
	Alg string `json:"alg"`
	Use string `json:"use"`
	Kid string `json:"kid"`
	X   string `json:"x"`
	D   string `json:"d"`
}

type jwkSet struct {
	Keys []jwk `json:"keys"`
}

func randBytes(n int) []byte {
	b := make([]byte, n)
	if _, err := rand.Read(b); err != nil {
		panic("crypto/rand failed")
	}
	return b
}

func newKid(now time.Time) string {
	return "k" + now.UTC().Format("20060102") + "-" + hex.EncodeToString(randBytes(3))
}

func newSigningKeys(kid string) (string, error) {
	seed := randBytes(ed25519.SeedSize)
	pub := ed25519.NewKeyFromSeed(seed).Public().(ed25519.PublicKey)
	set := jwkSet{Keys: []jwk{{
		Kty: "OKP", Crv: "Ed25519", Alg: "EdDSA", Use: "sig", Kid: kid,
		X: base64.RawURLEncoding.EncodeToString(pub),
		D: base64.RawURLEncoding.EncodeToString(seed),
	}}}
	b, err := json.Marshal(set)
	return string(b), err
}

func firstKid(setJSON string) (string, error) {
	var s jwkSet
	if err := json.Unmarshal([]byte(setJSON), &s); err != nil || len(s.Keys) == 0 || s.Keys[0].Kid == "" {
		return "", errors.New("JWT_SIGNING_KEYS is not a JSON key set with a kid")
	}
	return s.Keys[0].Kid, nil
}

// Generate returns NAME='value' lines for every missing app key and the names generated.
func Generate(existing map[string]string, now time.Time) (lines, names []string, err error) {
	have := func(n string) bool { return existing[n] != "" }
	add := func(n, v string) {
		lines = append(lines, n+"='"+v+"'")
		names = append(names, n)
	}
	kid := existing["JWT_CURRENT_KID"]
	if !have("JWT_SIGNING_KEYS") {
		if kid == "" {
			kid = newKid(now)
		}
		set, err := newSigningKeys(kid)
		if err != nil {
			return nil, nil, err
		}
		add("JWT_SIGNING_KEYS", set)
	} else if kid == "" {
		if kid, err = firstKid(existing["JWT_SIGNING_KEYS"]); err != nil {
			return nil, nil, err
		}
	}
	if !have("JWT_CURRENT_KID") {
		add("JWT_CURRENT_KID", kid)
	}
	for _, n := range AppKeys[2:] {
		if !have(n) {
			add(n, base64.StdEncoding.EncodeToString(randBytes(32)))
		}
	}
	return lines, names, nil
}

func runGenerate(args []string, out io.Writer) error {
	fs := flag.NewFlagSet("generate", flag.ExitOnError)
	envPath := fs.String("env", ".env.local", "env file to fill")
	_ = fs.Parse(args)
	ef, err := readEnv(*envPath)
	if err != nil {
		return err
	}
	lines, names, err := Generate(ef.Values, time.Now())
	if err != nil {
		return err
	}
	if len(lines) == 0 {
		return nil
	}
	if err := appendEnv(*envPath, lines); err != nil {
		return err
	}
	for _, n := range names {
		fmt.Fprintf(out, "generated: %s\n", n)
	}
	return nil
}

// ---------------------------------------------------------------- check

func runCheck(args []string, out io.Writer) error {
	fs := flag.NewFlagSet("check", flag.ExitOnError)
	envPath := fs.String("env", ".env.local", "local env file")
	examplePath := fs.String("example", ".env.example", "file listing every env var name")
	_ = fs.Parse(args)
	ex, err := readEnv(*examplePath)
	if err != nil {
		return err
	}
	local, err := readEnv(*envPath)
	if err != nil {
		return err
	}
	missingApp := 0
	for _, n := range ex.Order {
		state := "missing"
		if os.Getenv(n) != "" || local.Values[n] != "" {
			state = "set"
		}
		fmt.Fprintf(out, "%s %s\n", n, state)
		if state == "missing" && contains(AppKeys, n) {
			missingApp++
		}
	}
	if missingApp > 0 {
		return fmt.Errorf("%d app key(s) missing; run make setup", missingApp)
	}
	return nil
}

func contains(list []string, s string) bool {
	for _, v := range list {
		if v == s {
			return true
		}
	}
	return false
}

// ---------------------------------------------------------------- leakscan

// needles returns every printable form of a secret value worth searching for.
// Short values (under 8 characters) are skipped: they cannot be told apart from noise.
func needles(name, val string) map[string]string {
	forms := map[string]string{}
	addRaw := func(form string, b []byte) {
		if len(b) < 8 {
			return
		}
		forms[form+":std"] = base64.StdEncoding.EncodeToString(b)
		forms[form+":rawstd"] = base64.RawStdEncoding.EncodeToString(b)
		forms[form+":url"] = base64.URLEncoding.EncodeToString(b)
		forms[form+":rawurl"] = base64.RawURLEncoding.EncodeToString(b)
		forms[form+":hex"] = hex.EncodeToString(b)
		forms[form+":HEX"] = strings.ToUpper(hex.EncodeToString(b))
	}
	if len(val) >= 8 {
		forms["raw"] = val
	}
	if b, err := base64.StdEncoding.DecodeString(val); err == nil {
		addRaw("bytes", b)
	}
	if name == "JWT_SIGNING_KEYS" {
		var s jwkSet
		if json.Unmarshal([]byte(val), &s) == nil {
			for _, k := range s.Keys {
				if d, err := base64.RawURLEncoding.DecodeString(k.D); err == nil {
					addRaw("jwk.d", d)
				}
			}
		}
	}
	return forms
}

func runLeakscan(args []string, out io.Writer) error {
	fs := flag.NewFlagSet("leakscan", flag.ExitOnError)
	envPath := fs.String("env", ".env.local", "env file whose values must not appear")
	only := fs.String("names", strings.Join(AppKeys, ","), "comma-separated names to scan for (default: app keys)")
	_ = fs.Parse(args)
	ef, err := readEnv(*envPath)
	if err != nil {
		return err
	}
	names := strings.Split(*only, ",")
	sort.Strings(names)
	leaks := 0
	for _, file := range fs.Args() {
		data, err := os.ReadFile(file)
		if err != nil {
			return fmt.Errorf("read %s", file)
		}
		for _, n := range names {
			v := ef.Values[n]
			if v == "" || n == "JWT_CURRENT_KID" { // the kid is public by design (it is in every token header)
				continue
			}
			forms := needles(n, v)
			keys := make([]string, 0, len(forms))
			for k := range forms {
				keys = append(keys, k)
			}
			sort.Strings(keys)
			for _, form := range keys {
				if bytes.Contains(data, []byte(forms[form])) {
					fmt.Fprintf(out, "leak: %s in %s (%s)\n", n, file, form)
					leaks++
					break
				}
			}
		}
	}
	if leaks > 0 {
		return fmt.Errorf("%d leak(s) found", leaks)
	}
	return nil
}
